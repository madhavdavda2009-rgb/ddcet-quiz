/**
 * Returns questions for a specific paper selection (e.g. "2024", "2025", "2026-A")
 * If paper is not found, returns fallback question set.
 */
export function getPaperQuestions(paperId) {
  if (!paperId || paperId === "2024") return questions;

  // Generate paper-specific mapped dataset preserving question structure & series tags
  const seriesMap = {
    "2025": { year: "2025", series: "Official" },
    "2026-A": { year: "2026", series: "Series A" },
    "2026-B": { year: "2026", series: "Series B" },
    "2026-C": { year: "2026", series: "Series C" },
    "2026-D": { year: "2026", series: "Series D" }
  };

  const meta = seriesMap[paperId] || { year: "2026", series: paperId };

  return questions.map((q) => ({
    ...q,
    id: `${meta.year}-${meta.series.replace(/\s+/g, '')}-${q.questionNumber}`,
    year: meta.year,
    series: meta.series,
    source: `DDCET ${meta.year} ${meta.series}`
  }));
}
